  ///           I-4.1.01.01 (Venta), G-5.1.01 (Sueldos), C-6.1.01.01 (CMV).
  static String buildId(AccountType type, String code) {
    final prefix = switch (type) {
      AccountType.activo => 'A',
      AccountType.pasivo => 'P',
      AccountType.patrimonio => 'PAT',
      AccountType.ingreso => 'I',
      AccountType.gasto => 'G',
      AccountType.costo => 'C',
    };
    return '$prefix-$code';
  }

