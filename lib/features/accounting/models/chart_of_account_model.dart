  ChartOfAccountModel({
    required this.id,
    required this.code,
    required this.name,
    required this.type,
    required this.nature,
    this.parentId,
    this.isLeaf = true,
    this.balance = 0.0,
    this.isActive = true,
    this.description,
  });

  Map<String, dynamic> toMap() {
    return {
      'code': code,
      'name': name,
      'type': type.name,
      'nature': nature.name,
      'parentId': parentId,
      'isLeaf': isLeaf,
      'balance': balance,
      'isActive': isActive,
      'description': description,
    };
  }

  factory ChartOfAccountModel.fromMap(Map<String, dynamic> map, String docId) {
    return ChartOfAccountModel(
      id: docId,
      code: map['code'] ?? '',
      name: map['name'] ?? '',
      type: AccountType.values.byName(map['type'] ?? 'activo'),
      nature: AccountNature.values.byName(map['nature'] ?? 'deudora'),
      parentId: map['parentId'],
      isLeaf: map['isLeaf'] ?? true,
      balance: (map['balance'] as num?)?.toDouble() ?? 0.0,
      isActive: map['isActive'] ?? true,
      description: map['description'],
    );
  }

